"""
Tiny authoring helper for built-in maps.

Maps are described room-by-room (rectangles, doors, props, entities) and
emitted as the ASCII format consumed by shared/src/map/builtin/ascii.ts.
Run:  python tools/mapgen/build_maps.py
"""


class Canvas:
    def __init__(self, w, d, floors=1, fill="#"):
        self.w, self.d = w, d
        self.g = [[[fill] * w for _ in range(d)] for _ in range(floors)]

    # ── primitives ─────────────────────────────────────────────
    def set(self, f, x, z, ch):
        assert 0 <= x < self.w and 0 <= z < self.d, (f, x, z, ch)
        self.g[f][z][x] = ch

    def get(self, f, x, z):
        return self.g[f][z][x]

    def fill(self, f, x0, z0, x1, z1, ch):
        for z in range(min(z0, z1), max(z0, z1) + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                self.set(f, x, z, ch)

    def room(self, f, x0, z0, x1, z1, floor="."):
        """Carve an interior rectangle (inclusive). Walls are whatever surrounds it."""
        self.fill(f, x0, z0, x1, z1, floor)

    def void(self, f, x0, z0, x1, z1):
        self.fill(f, x0, z0, x1, z1, " ")

    def put(self, f, x, z, ch):
        """Place an entity/prop glyph on a carved cell."""
        assert self.get(f, x, z) not in "# ", f"entity {ch} at {x},{z} f{f} is on '{self.get(f, x, z)}'"
        self.set(f, x, z, ch)

    def puts(self, f, pts, ch):
        for x, z in pts:
            self.put(f, x, z, ch)

    def row_of(self, f, z, x0, x1, ch, step=1):
        for x in range(x0, x1 + 1, step):
            self.put(f, x, z, ch)

    def col_of(self, f, x, z0, z1, ch, step=1):
        for z in range(z0, z1 + 1, step):
            self.put(f, x, z, ch)

    # ── output ─────────────────────────────────────────────────
    def rows(self, f):
        return ["".join(r) for r in self.g[f]]

    def emit_ts(self, path, const, meta, legend=None, light_colors=None):
        floors = []
        for f in range(len(self.g)):
            rows = self.rows(f)
            floors.append("    `\n" + "\n".join(rows) + "\n`")
        legend_ts = ""
        if legend:
            legend_ts = "  legend: { " + ", ".join(f'{k}: "{v}"' for k, v in legend.items()) + " },\n"
        lc = ""
        if light_colors:
            lc = "  lightColors: [" + ", ".join(f'"{c}"' for c in light_colors) + "],\n"
        L = meta["lighting"]
        ts = (
            'import { buildAsciiMap } from "./ascii.js";\n\n'
            f"/**\n * {meta['name']}: {meta['blurb']}\n * Generated by tools/mapgen/build_maps.py; edit the generator, not this file.\n */\n"
            f"export const {const} = buildAsciiMap({{\n"
            f'  id: "{meta["id"]}",\n'
            f'  name: "{meta["name"]}",\n'
            f'  description: "{meta["description"]}",\n'
            f'  theme: "{meta["theme"]}",\n'
            f'  lighting: {{ ambient: "{L[0]}", ambientIntensity: {L[1]}, fog: "{L[2]}", fogDensity: {L[3]}, sky: "{L[4]}", lamp: {L[5]} }},\n'
            f"{lc}{legend_ts}"
            "  floors: [\n" + ",\n".join(floors) + ",\n  ],\n});\n"
        )
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(ts)

    def preview(self):
        for f in range(len(self.g)):
            print(f"--- floor {f}")
            print("\n".join(self.rows(f)))
